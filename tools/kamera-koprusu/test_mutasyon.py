# (22.11 takip_bulucu_geri_geldi). Hata satırları önce, sonra kuyruk.
_HATA_ISARETLERI = ("FAIL", "BAŞARISIZ", "Traceback", "Error")


def _ozet(metin: str, kuyruk: int = 600, en_cok: int = 20) -> str:
    satirlar = [s for s in metin.splitlines() if any(i in s for i in _HATA_ISARETLERI)]
    son = metin[-kuyruk:]
    satirlar = [s for s in satirlar[:en_cok] if s not in son]
    return ("\n".join(satirlar) + "\n…\n" + son) if satirlar else son


